const API_KEY = "bgXqQYEMzjhxLkhc5aKvcdxtsPuYbF0sg3DvvBZc";

async function fetchProducts() {
  console.log("Fetching products from Printful...");

  const res = await fetch("https://api.printful.com/store/products?limit=100", {
    headers: { Authorization: `Bearer ${API_KEY}` },
  });
  const json = await res.json();
  const result = json.result;

  console.log(`Found ${result.length} products. Fetching details...`);
  console.log("First product sample:", JSON.stringify(result[0], null, 2));

  const products = [];

  for (const item of result) {
    const detailRes = await fetch(`https://api.printful.com/store/products/${item.id}`, {
      headers: { Authorization: `Bearer ${API_KEY}` },
    });
    const json = await detailRes.json();
    const detail = json.result;

    // Handle both object and array responses
    const productData = Array.isArray(detail) ? detail[0] : detail;

    if (!productData || !productData.sync_product) {
      console.log(`  ⚠ Skipping product ${item.id}`);
      continue;
    }

    const sync_product = productData.sync_product;
    const sync_variants = productData.sync_variants || [];

    // Collect unique sizes from variants
    const sizes = [...new Set(
      sync_variants
        .map((v) => v.name?.split(" / ").pop()?.trim())
        .filter(Boolean)
    )];

    // Get price from first variant
    const price = sync_variants[0]?.retail_price
      ? parseFloat(sync_variants[0].retail_price)
      : 0;

    // Slug-friendly ID
    const id = sync_product.name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, "");

    products.push({
      id,
      name: sync_product.name,
      nameUrdu: "", // fill in manually
      collection: guessCollection(sync_product.name),
      price,
      description: "",
      images: sync_product.thumbnail_url ? [sync_product.thumbnail_url] : [],
      stripeLink: "https://buy.stripe.com/REPLACE_ME",
      sizes: sizes.length ? sizes : ["S", "M", "L", "XL", "XXL"],
      isLimitedDrop: false,
      isSoldOut: sync_product.is_ignored || false,
      printfulId: sync_product.id,
    });

    console.log(`  ✓ ${sync_product.name} — $${price} — ${sizes.join(", ")}`);
  }

  return products;
}

function guessCollection(name) {
  const lower = name.toLowerCase();
  if (lower.includes("hoodie")) return "hoodies";
  if (lower.includes("sweatshirt") || lower.includes("crewneck")) return "sweatshirts";
  if (lower.includes("t-shirt") || lower.includes("tee") || lower.includes("tshirt")) return "tshirts";
  if (lower.includes("embroid")) return "embroidery";
  return "limited";
}

